/**
 * Writes `src/version.ts` from `package.json` and the installed Pi Durable, so the running Worker can say which
 * build it is (`/api/health`, the startup guard's messages, `app_meta`).
 *
 *   node scripts/stamp-version.ts           write it
 *   node scripts/stamp-version.ts --check   fail if it is out of date (part of `pnpm check`)
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path: string): { version: string } =>
  JSON.parse(readFileSync(new URL(path, root), "utf8")) as { version: string };

const mipi = read("package.json").version;
const piDurable = read("node_modules/@earendil-works/pi-durable/package.json").version;

const content = `// Generated by scripts/stamp-version.ts from package.json and the installed pi-durable. Do not edit.
export const MIPI_VERSION = ${JSON.stringify(mipi)};
export const PI_DURABLE_VERSION = ${JSON.stringify(piDurable)};
`;

const target = new URL("src/version.ts", root);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing counts as out of date.
  }
  if (current !== content) {
    console.error("src/version.ts is out of date. Run `node scripts/stamp-version.ts`.");
    process.exit(1);
  }
} else {
  writeFileSync(target, content);
  console.log(`src/version.ts: MiPi ${mipi}, Pi Durable ${piDurable}`);
}
